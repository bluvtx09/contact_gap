"""ISO 기준과 시뮬 측정의 접점.

ISO/TS 15066 (2025년 ISO 10218-2에 흡수됨)의 유도 경로:

    부위별 최대 힘 f_max, 유효 스프링상수 k
      → 최대 허용 에너지  E_max = f_max² / (2k)
      → 최대 허용 속도    E = ½·μ·v_rel²  에서 역산

이 경로는 **접촉 전 운동학**(환산질량, 상대속도)만 쓴다.
접촉력을 시뮬레이션하지 않는다.

그런데 실무 준수 입증은 접촉력 측정 또는 '검증된 시뮬레이션 데이터'로 한다.
발견 6에서 시뮬 최대력은 엔진 간 7~13배 갈렸다.

여기서 묻는 것: 같은 충돌에 대해
  (a) ISO의 에너지 경로로 낸 판정과
  (b) 각 엔진의 시뮬 최대력으로 낸 판정이
얼마나 어긋나는가?
"""

import numpy as np

# ISO/TS 15066 Annex A (ISO 10218-2:2025에 수록) — 준정적 접촉 기준.
# 과도 접촉 한계는 통상 준정적의 2배로 적용된다.
BODY = {
    #  부위          f_max[N]  k[N/mm]  유효질량[kg]
    "얼굴":            (65,     75,     4.4),
    "두개골·이마":      (130,    150,    4.4),
    "가슴":            (140,    25,     40),
    "복부":            (110,    10,     40),
    "손·손가락":        (140,    75,     0.6),
    "위팔·팔꿈치":      (150,    30,     3),
}

# 우리 팔의 접촉점 기하
L = 0.30
ARM_MASS = 0.45
R_CONTACT = 0.287        # 관절축에서 접촉점까지 [m]
I_ARM = ARM_MASS * L * L / 3


def m_eff_robot():
    """접촉점에서 본 로봇 유효질량 [kg]."""
    return I_ARM / (R_CONTACT ** 2)


def iso_max_speed(region):
    """ISO 경로로 구한 최대 허용 관절 각속도 [rad/s]."""
    f_max, k_mm, m_h = BODY[region]
    k = k_mm * 1000.0                       # N/m
    e_max = f_max ** 2 / (2 * k)            # J
    m_r = m_eff_robot()
    mu = 1.0 / (1.0 / m_r + 1.0 / m_h)      # 환산질량 [kg]
    v_rel = np.sqrt(2 * e_max / mu)         # m/s
    return v_rel / R_CONTACT, e_max, mu, v_rel


def main():
    print("=" * 76)
    print("ISO 에너지 경로 — 접촉력 시뮬 없이 구하는 허용 속도")
    print("=" * 76)
    m_r = m_eff_robot()
    print(f"\n팔 접촉점 유효질량 {m_r:.3f} kg, 접촉 반경 {R_CONTACT} m\n")
    print(f"{'신체 부위':<14}{'f_max':>8}{'k':>10}{'E_max':>10}"
          f"{'환산질량':>10}{'허용 v_rel':>12}{'허용 각속도':>13}")
    print("-" * 76)
    for region in BODY:
        w, e_max, mu, v_rel = iso_max_speed(region)
        f_max, k_mm, _ = BODY[region]
        print(f"{region:<14}{f_max:6d} N{k_mm:8.0f}{e_max:9.3f} J"
              f"{mu:9.3f} kg{v_rel:10.2f} m/s{w:11.2f} rad/s")
    print("-" * 76)
    print("\n이 값들은 어느 시뮬레이터도 쓰지 않고 나온다.")
    print("접촉 전 운동학과 표준의 인체 모델만으로 결정된다.")

    print(f"\n{'=' * 76}")
    print("대조: 시뮬 최대력으로 낸 허용 속도 (가슴 기준 140 N)")
    print("=" * 76)
    print("""
발견 6에서 잰 같은 충돌의 엔진별 최대력 (v0 = 9 rad/s, dt = 0.2 ms):

    MuJoCo    150.4 N   → 문턱 초과
    PyBullet 1500.7 N   → 문턱 초과 (10배)
    Drake     797.0 N   → 문턱 초과 (5배)

세 엔진이 판정은 같지만 여유율이 전혀 다르다.
설계 판단(속도를 얼마나 낮춰야 하는가)은 완전히 갈린다.""")

    w_chest, _, _, _ = iso_max_speed("가슴")
    print(f"""
ISO 경로로 구한 가슴 기준 허용 각속도: {w_chest:.2f} rad/s

4차 실험에서 MuJoCo로 잰 실물 한계속도는 8.6 rad/s였다.
ISO 해석해와 {abs(8.6 - w_chest) / w_chest * 100:.0f}% 차이다.

즉 ISO 경로는 시뮬 없이도 같은 자릿수의 답을 준다.
반면 시뮬 최대력 경로는 엔진에 따라 5~10배 갈린다.""")

    print(f"\n{'=' * 76}")
    print("함의")
    print("=" * 76)
    print("""
표준이 요구하는 것은 '접촉력이 한계 이하'라는 입증이다.
그 입증을 시뮬 최대력으로 하면, 엔진 선택이 결과를 좌우한다.

반면 표준 자신의 유도 경로(에너지)는 접촉 모델을 타지 않는다.
검증된 시뮬레이션 데이터로 준수를 입증하려는 쪽은
최대력이 아니라 에너지·충격량을 보고해야 한다.

주의: ISO 경로는 완전 비탄성 충돌과 선형 스프링 인체 모델을 가정한다.
탄성 접촉부나 반발이 있는 충돌에서는 보수적이지 않을 수 있다.
이 대조는 '어느 쪽이 옳다'가 아니라
'둘이 다른 답을 주며, 한쪽만 엔진에 의존한다'는 것을 보인다.""")


if __name__ == "__main__":
    main()
